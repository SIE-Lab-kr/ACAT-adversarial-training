"""
Professional LaTeX (booktabs, IEEEtran-style) tables spanning ALL 5 backbones
x ALL 7 datasets (v6): a protocol table and a main-results table.

Table I (protocol): one row per (dataset, backbone) -- epochs, batch size,
learning rate, LR schedule, adversarial-training eps/alpha/steps, and real
parameter counts (computed by actually instantiating each backbone for each
dataset's real channel/class-count metadata, src.models.build_model -- not
copied from documentation), for every one of the 35 (dataset, backbone)
pairs this codebase supports. Settings come straight from configs/*.yaml (the
paper's stated per-dataset protocol); the backbone varies across all 5 this
codebase implements, not just the one backbone each config names.

Table II (results): reads a long-format results CSV (the schema
run_full_gpu_matrix.py / run_full_matrix_v5.py write: dataset, backbone,
method, clean_acc, fgsm_acc, pgd20_acc, apgd20_acc, cw_linf_acc,
square_bbox_acc, transfer_bbox_acc, mean_robust_acc, MES, ...) and renders it
as a grouped booktabs table (multirow by dataset, then by backbone), with
ACAT's row bolded where it has the best MES in its (dataset, backbone) group.
Whatever scale the CSV was produced at (this session's CPU validation slice,
or a full run_full_gpu_matrix.py GPU run) is stated in the table's own
footnote, read from the CSV itself -- never hand-typed -- so the table never
silently overstates its own scale.

Usage:
    python make_professional_tables.py --results_csv results_gpu_matrix_quick/comparison_summary_full_v6.csv
"""
import os
import sys
import csv
import argparse

sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
from src.models import build_model, BACKBONES
from src.data import DATASET_INFO
from run_full_gpu_matrix import load_dataset_config, ALL_DATASETS

OUT_DIR = "tables"
os.makedirs(OUT_DIR, exist_ok=True)

DATASET_LABELS = {"cifar10": "CIFAR-10", "cifar100": "CIFAR-100", "fashionmnist": "Fashion-MNIST",
                   "tinyimagenet": "Tiny-ImageNet", "svhn": "SVHN", "gtsrb": "GTSRB", "stl10": "STL-10"}
BACKBONE_LABELS = {"smallcnn": "SmallCNN", "wrn28_10": "WideResNet-28-10", "resnet18": "ResNet-18",
                    "vgg11": "VGG-11", "mobilenet": "MobileNet"}
METHOD_LABELS = {"standard": "Standard", "pgd_at": "PGD-AT", "trades": "TRADES", "mart": "MART", "acat": "ACAT (ours)"}


def n_params(dataset, backbone, width=32):
    info = DATASET_INFO[dataset]
    net = build_model(info, width=width, backbone=backbone)
    return sum(p.numel() for p in net.parameters())


def make_table1(datasets=ALL_DATASETS, backbones=BACKBONES, out_name="table1_protocol_full.tex"):
    lines = []
    lines.append(f"% Table I -- full protocol, all {len(backbones)} backbones x "
                 f"all {len(datasets)} datasets ({len(datasets) * len(backbones)} rows).")
    lines.append(r"% Auto-generated by make_professional_tables.py -- epochs/batch/lr/schedule/eps come from")
    lines.append(r"% configs/<dataset>.yaml; parameter counts are computed by instantiating each backbone.")
    lines.append(r"\begin{table*}[t]")
    lines.append(r"\centering")
    lines.append(r"\caption{Full training protocol for every (dataset, backbone) pair this codebase supports. "
                 r"Epochs, batch size, learning rate, schedule, and adversarial-training $\epsilon/\alpha$/steps "
                 r"are the paper's per-dataset protocol (\texttt{configs/<dataset>.yaml}); parameter counts are "
                 r"real, computed per dataset (class count changes the classifier head size).}")
    lines.append(r"\label{tab:protocol_full}")
    lines.append(r"\begin{tabular}{l l r r r r l r r r}")
    lines.append(r"\toprule")
    lines.append(r"Dataset & Backbone & Params (M) & Epochs & Batch & LR & Schedule & "
                 r"$\epsilon$ & $\alpha$ & Adv.\ steps \\")
    lines.append(r"\midrule")
    for di, dataset in enumerate(datasets):
        cfg = load_dataset_config(dataset)
        for bi, backbone in enumerate(backbones):
            params_m = n_params(dataset, backbone) / 1e6
            dname = DATASET_LABELS[dataset] if bi == 0 else ""
            row = (f"{dname} & {BACKBONE_LABELS[backbone]} & {params_m:.2f} & {cfg['epochs']} & "
                   f"{cfg['batch_size']} & {cfg['lr']:g} & {cfg['lr_schedule']} & "
                   f"{cfg['train_eps']:.4f} & {cfg['train_alpha']:.4f} & {cfg['train_steps']} \\\\")
            lines.append(row)
        if di < len(datasets) - 1:
            lines.append(r"\midrule")
    lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(r"\end{table*}")

    out = os.path.join(OUT_DIR, out_name)
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("Saved", out)


def make_table2(results_csv, out_name="table2_results_full.tex", metrics=("clean_acc", "pgd20_acc", "MES")):
    with open(results_csv) as f:
        rows = list(csv.DictReader(f))
    if not rows:
        print(f"{results_csv} has no rows -- nothing to render. Skipping Table II.")
        return

    has_dataset = "dataset" in rows[0]
    datasets = sorted(set(r["dataset"] for r in rows)) if has_dataset else [None]
    backbones_present = sorted(set(r["backbone"] for r in rows), key=lambda b: BACKBONES.index(b) if b in BACKBONES else 99)
    methods_present = sorted(set(r["method"] for r in rows),
                              key=lambda m: list(METHOD_LABELS.keys()).index(m) if m in METHOD_LABELS else 99)

    # scale/provenance footnote, read from the data itself -- never hand-typed
    epochs_seen = sorted(set(str(r.get("epochs", "")) for r in rows) - {"", "None"})
    devices_seen = sorted(set(str(r.get("device", "")) for r in rows) - {"", "None"})
    epochs_str = ",".join(epochs_seen) if epochs_seen else "not recorded in this CSV"
    device_str = ",".join(devices_seen) if devices_seen else "not recorded in this CSV"

    lines = []
    lines.append(f"% Table II -- results across {len(datasets) if has_dataset else 1} dataset(s), "
                 f"{len(backbones_present)} backbone(s), {len(methods_present)} method(s), {len(rows)} rows.")
    lines.append(f"% Auto-generated by make_professional_tables.py from {os.path.basename(results_csv)}.")
    lines.append(r"% Requires \usepackage{multirow} in the preamble (already used by this paper's Table VIII).")
    lines.append(r"\begin{table*}[t]")
    lines.append(r"\centering")
    metric_label = {"clean_acc": "Clean", "pgd20_acc": "PGD-20", "fgsm_acc": "FGSM", "apgd20_acc": "APGD-20",
                     "cw_linf_acc": "CW-Linf", "square_bbox_acc": "Square", "transfer_bbox_acc": "Transfer",
                     "mean_robust_acc": "Mean robust", "MES": "MES"}
    metric_cols = " & ".join(metric_label.get(m, m) for m in metrics)
    lines.append(r"\caption{Results across all evaluated (dataset, backbone, method) cells "
                 f"(epochs={epochs_str}; device={device_str}). "
                 r"Best MES within each (dataset, backbone) group is \textbf{bolded}. "
                 r"See the accompanying execution log for the honest scale of this table (validation-scale here "
                 r"unless produced by a full run\_full\_gpu\_matrix.py GPU run).}")
    lines.append(r"\label{tab:results_full}")
    col_spec = ("l " if has_dataset else "") + "l l " + " ".join(["r"] * len(metrics))
    lines.append(r"\begin{tabular}{" + col_spec + r"}")
    lines.append(r"\toprule")
    header = ("Dataset & " if has_dataset else "") + f"Backbone & Method & {metric_cols} \\\\"
    lines.append(header)
    lines.append(r"\midrule")

    for dataset in datasets:
        d_rows = [r for r in rows if (not has_dataset or r["dataset"] == dataset)]
        d_backbones = [b for b in backbones_present if any(r["backbone"] == b for r in d_rows)]
        d_row_count = sum(1 for b in d_backbones for r in d_rows if r["backbone"] == b)
        dataset_row_used = False
        for backbone in d_backbones:
            b_rows = {r["method"]: r for r in d_rows if r["backbone"] == backbone}
            b_methods = [m for m in methods_present if m in b_rows]
            if not b_methods:
                continue
            best_method = max(b_methods, key=lambda m: float(b_rows[m].get("MES", 0) or 0))
            backbone_row_used = False
            for method in b_methods:
                r = b_rows[method]
                vals = []
                for metric in metrics:
                    v = r.get(metric, "")
                    vals.append(f"{float(v):.1f}" if v not in ("", None) else "--")
                is_best = (method == best_method)
                method_cell = METHOD_LABELS.get(method, method)
                val_cells = " & ".join(vals)
                if is_best:
                    method_cell = r"\textbf{" + method_cell + "}"
                    val_cells = " & ".join(r"\textbf{" + v + "}" for v in vals)
                prefix = ""
                if has_dataset:
                    if not dataset_row_used:
                        dname = DATASET_LABELS.get(dataset, dataset)
                        prefix += r"\multirow{" + str(d_row_count) + "}{*}{" + dname + "} & "
                        dataset_row_used = True
                    else:
                        prefix += " & "
                if not backbone_row_used:
                    bname = BACKBONE_LABELS.get(backbone, backbone)
                    prefix += r"\multirow{" + str(len(b_methods)) + "}{*}{" + bname + "} & "
                    backbone_row_used = True
                else:
                    prefix += " & "
                lines.append(f"{prefix}{method_cell} & {val_cells} \\\\")
        lines.append(r"\midrule")
    if lines[-1] == r"\midrule":
        lines[-1] = r"\bottomrule"
    else:
        lines.append(r"\bottomrule")
    lines.append(r"\end{tabular}")
    lines.append(r"\end{table*}")

    out = os.path.join(OUT_DIR, out_name)
    with open(out, "w") as f:
        f.write("\n".join(lines) + "\n")
    print("Saved", out, f"({len(rows)} rows rendered)")


def main():
    p = argparse.ArgumentParser()
    p.add_argument("--results_csv", default=None, help="omit to skip Table II and render only Table I")
    p.add_argument("--datasets", default=",".join(ALL_DATASETS))
    p.add_argument("--backbones", default=",".join(BACKBONES))
    args = p.parse_args()

    make_table1(datasets=args.datasets.split(","), backbones=args.backbones.split(","))
    if args.results_csv:
        make_table2(args.results_csv)
    else:
        print("No --results_csv given -- skipped Table II.")


if __name__ == "__main__":
    main()
